# Convert haven_labelled to plain; keep character for USUBJID/PARCAT1
adpc <- adpc %>%
  mutate(across(everything(), ~ {
    if (inherits(.x, "haven_labelled")) {
      # preserve character labelled as character, numeric as numeric
      v <- as.character(.x)
      # try numeric conversion if original is numeric
      suppressWarnings({
        nv <- as.numeric(v)
        # if conversion loses info, keep character
        if (all(is.na(nv) == is.na(.x)) || is.numeric(.x)) as.numeric(.x) else v
      })
    } else .x
  }))

adpc$USUBJID <- as.character(adpc$USUBJID)
adpc$PARCAT1 <- as.character(adpc$PARCAT1)

# FIX: EACTM is character in ADPC (e.g. "96.0333333" and "" for missing)
# SAS GPLOT uses numeric axis; R scale_x_continuous fails on discrete character.
# Convert EACTM to numeric once, with "" -> NA, trimming whitespace.
adpc$EACTM <- trimws(as.character(adpc$EACTM))
adpc$EACTM[adpc$EACTM == ""] <- NA
adpc$EACTM <- suppressWarnings(as.numeric(adpc$EACTM))

# AVAL also ensure numeric
adpc$AVAL <- suppressWarnings(as.numeric(as.character(adpc$AVAL)))

