# P060 - Individual PK concentration-time profiles (translation of P060_pk_subj_conc.sas)
suppressPackageStartupMessages({
  library(haven)
  library(dplyr)
  library(ggplot2)
})

out <- Sys.getenv("OUT_DIR")
if (out == "") out <- "."
dir.create(out, showWarnings = FALSE, recursive = TRUE)

rawadam <- "D:/meta_hackathon/sas2r-agent/data/raw/cdisc-pilot/adam"

# ---- data work.adsl / work.adpc ----
adsl <- read_xpt(file.path(rawadam, "adsl.xpt"))
adpc <- read_xpt(file.path(rawadam, "adpc.xpt"))
names(adpc) <- toupper(names(adpc))

# Make sure the BY / plot variables exist (case-insensitive in SAS)
need <- c("USUBJID", "PARCAT1", "EACTM", "AVAL")
for (v in need) {
  if (!v %in% names(adpc)) {
    message("Variable ", v, " not found in ADPC; creating as missing")
    adpc[[v]] <- if (v %in% c("USUBJID", "PARCAT1")) "" else NA_real_
  }
}
adpc <- adpc %>%
  mutate(USUBJID = as.character(USUBJID),
         PARCAT1 = as.character(PARCAT1),
         EACTM   = as.numeric(EACTM),
         AVAL    = as.numeric(AVAL))
adpc$USUBJID[is.na(adpc$USUBJID)] <- ""
adpc$PARCAT1[is.na(adpc$PARCAT1)] <- ""

# ---- PROC SORT BY USUBJID parcat1 eactm (C-locale ordering, missing first, stable) ----
ord <- order(adpc$USUBJID, adpc$PARCAT1,
             !is.na(adpc$EACTM), adpc$EACTM,
             method = "radix", na.last = TRUE)
sortadpc <- adpc[ord, , drop = FALSE]

# ---- plotted data ----
plotdat <- sortadpc %>%
  select(USUBJID, PARCAT1, EACTM, AVAL) %>%
  mutate(BYGROUP = paste0("USUBJID=", USUBJID, " PARCAT1=", PARCAT1))

grp_levels <- unique(plotdat$BYGROUP)
plotdat$PAGE <- match(plotdat$BYGROUP, grp_levels)

write.csv(plotdat, file.path(out, "sasgraph.csv"), row.names = FALSE, na = "")

titles <- c("(page x of x)",
            "Figure 16.2.5-x.x Individual concentration-time profiles",
            "by compound, matrix, analyte and [actual/randomised][treatments/group]",
            "Analysis Set : PK analysis set")
footnote <- paste0("Generated by the R System on ",
                   format(Sys.Date(), "%B %d, %Y"), " at ",
                   format(Sys.time(), "%I:%M:%S %p"))

make_plot <- function(d) {
  d <- d[!is.na(d$EACTM) & !is.na(d$AVAL), , drop = FALSE]
  ggplot(d, aes(x = EACTM, y = AVAL)) +
    geom_line(linewidth = 0.8, colour = "#2A25D9") +
    labs(title = paste(titles, collapse = "\n"),
         x = "Time (hour)", y = "Conc (ug/mL)", caption = footnote) +
    theme_bw() +
    theme(plot.title = element_text(hjust = 0.5, size = 10),
          panel.grid = element_blank(),
          panel.border = element_rect(colour = "black", fill = NA))
}

# PROC GPLOT with BY -> one page per BY group; first page is sasgraph.png
if (length(grp_levels) == 0) {
  p <- ggplot() + labs(title = paste(titles, collapse = "\n"),
                       x = "Time (hour)", y = "Conc (ug/mL)") + theme_bw()
  ggsave(file.path(out, "sasgraph.png"), p, width = 8, height = 6, dpi = 100)
} else {
  for (i in seq_along(grp_levels)) {
    d <- plotdat[plotdat$PAGE == i, , drop = FALSE]
    p <- make_plot(d)
    fname <- if (i == 1) "sasgraph.png" else paste0("sasgraph", i - 1, ".png")
    ggsave(file.path(out, fname), p, width = 8, height = 6, dpi = 100)
  }
}

message("P060 done: ", length(grp_levels), " BY-group page(s) written")
