# P033 - Individual concentration-time profiles (PROC GPLOT by USUBJID PARCAT1)
suppressPackageStartupMessages({
  library(haven)
  library(dplyr)
  library(ggplot2)
})

out <- Sys.getenv("OUT_DIR")
if (out == "") out <- "."
dir.create(out, showWarnings = FALSE, recursive = TRUE)

rawadam <- "/bench/data/raw/cdisc-pilot/adam"

# ---- data work.adsl / work.adpc ----
adsl <- read_xpt(file.path(rawadam, "adsl.xpt"))
adpc <- read_xpt(file.path(rawadam, "adpc.xpt"))
names(adpc) <- toupper(names(adpc))
message("ADPC read: ", nrow(adpc), " rows")

# Drop SAS labels/formats so the column types are plain
adpc <- zap_labels(zap_formats(adpc))

# ---- PROC SORT by USUBJID PARCAT1 EACTM ----
# SAS sorts missing values first and compares character values byte-wise
# (C locale), so uppercase sorts before lowercase.
sas_key_chr <- function(x) {
  x <- as.character(x)
  x[is.na(x)] <- ""
  x
}

ord <- order(
  sas_key_chr(adpc$USUBJID),
  sas_key_chr(adpc$PARCAT1),
  !is.na(adpc$EACTM),
  adpc$EACTM,
  method = "radix"
)
sortadpc <- adpc[ord, , drop = FALSE]

# ---- Plotted data (GPLOT ignores points with missing X or Y) ----
plotdat <- sortadpc %>%
  filter(!is.na(AVAL), !is.na(EACTM)) %>%
  select(USUBJID, PARCAT1, EACTM, AVAL)

write.csv(plotdat, file.path(out, "sasgraph.csv"), row.names = FALSE, na = "")

# ---- Titles and footnote ----
titles <- paste(
  "(page x of x)",
  "Figure 16.2.5-x.x Individual concentration-time profiles",
  "by compound, matrix, analyte and [actual/randomised][treatments/group]",
  "Analysis Set : PK analysis set",
  sep = "\n"
)
foot <- paste0(
  "Generated by the SAS System (R, ", R.version$platform, ") on ",
  format(Sys.Date(), "%B %d, %Y"), " at ", format(Sys.time(), "%I:%M:%S %p")
)

# One graph per BY group (NOBYLINE: no by-line is shown)
make_plot <- function(d) {
  ggplot(d, aes(x = EACTM, y = AVAL)) +
    geom_line(linewidth = 0.8, colour = "#2A25D9") +
    labs(x = "Time (hour)", y = "Conc (ug/mL)", title = titles, caption = foot) +
    theme_bw() +
    theme(
      plot.title = element_text(hjust = 0.5, size = 10),
      plot.caption = element_text(hjust = 0, size = 7),
      panel.grid = element_blank(),
      panel.border = element_rect(colour = "black", fill = NA)
    )
}

grp <- plotdat %>% distinct(USUBJID, PARCAT1)

if (nrow(grp) == 0) {
  p <- ggplot() +
    labs(title = titles, caption = foot) +
    theme_bw()
  ggsave(file.path(out, "sasgraph.png"), p, width = 8, height = 6, dpi = 100)
} else {
  for (i in seq_len(nrow(grp))) {
    d <- plotdat %>%
      filter(USUBJID == grp$USUBJID[i], PARCAT1 == grp$PARCAT1[i])
    fn <- if (i == 1) "sasgraph.png" else paste0("sasgraph", i - 1, ".png")
    ggsave(file.path(out, fn), make_plot(d), width = 8, height = 6, dpi = 100)
  }
}

message("Done: ", nrow(grp), " by-group graph(s) written")
