# P060_pk_subj_conc.sas -> R translation
# Individual concentration-time profiles (GPLOT AVAL*eactm BY USUBJID parcat1)

suppressPackageStartupMessages({
  library(haven)
  library(dplyr)
  library(ggplot2)
})

out <- Sys.getenv("OUT_DIR")
if (out == "") out <- getwd()
dir.create(out, showWarnings = FALSE, recursive = TRUE)

root <- "D:/meta_hackathon/sas2r-agent"
rawadam <- "D:/meta_hackathon/sas2r-agent/data/raw/cdisc-pilot/adam"

adsl_path <- file.path(rawadam, "adsl.xpt")
adpc_path <- file.path(rawadam, "adpc.xpt")

cat("Reading ADSL:", adsl_path, "\n")
adsl <- haven::read_xpt(adsl_path)
cat("Reading ADPC:", adpc_path, "\n")
adpc <- haven::read_xpt(adpc_path)

# Helper: case-insensitive column lookup (SAS is case-insensitive)
find_var <- function(df, target) {
  idx <- which(toupper(names(df)) == toupper(target))
  if (length(idx) == 0) return(NA_character_)
  names(df)[idx[1]]
}

usubjid_c <- find_var(adpc, "USUBJID")
parcat1_c <- find_var(adpc, "PARCAT1")
eactm_c   <- find_var(adpc, "EACTM")
aval_c    <- find_var(adpc, "AVAL")

if (is.na(usubjid_c)) stop("USUBJID not found in ADPC")
if (is.na(parcat1_c)) stop("PARCAT1 not found in ADPC")
if (is.na(eactm_c))   stop("EACTM not found in ADPC")
if (is.na(aval_c))    stop("AVAL not found in ADPC")

cat("Using columns:", usubjid_c, parcat1_c, eactm_c, aval_c, "\n")

# PROC SORT DATA=WORK.ADPC OUT=WORK.SORTadpc; BY USUBJID parcat1 eactm; RUN;
# SAS semantics: missing sorts first; character ordering uppercase before lowercase
SORTadpc <- adpc
ord <- order(SORTadpc[[usubjid_c]], SORTadpc[[parcat1_c]], SORTadpc[[eactm_c]],
             na.last = FALSE, method = "radix")
SORTadpc <- SORTadpc[ord, , drop = FALSE]

cat("Sorted ADPC rows:", nrow(SORTadpc), "\n")

# CSV of plotted data (for figure traceability)
# Keep BY + plot variables with original SAS names (uppercase)
plot_data <- SORTadpc[, c(usubjid_c, parcat1_c, eactm_c, aval_c), drop = FALSE]
# Ensure standard names for CSV header matching SAS dataset variable names
names(plot_data) <- c("USUBJID", "PARCAT1", "EACTM", "AVAL")

# Write full sorted dataset as well for reference (dataset output)
write.csv(SORTadpc, file.path(out, "SORTadpc.csv"), row.names = FALSE, na = "")
write.csv(plot_data, file.path(out, "sasgraph.csv"), row.names = FALSE, na = "")
cat("Wrote SORTadpc.csv and sasgraph.csv\n")

# Prepare faceting variable: BY USUBJID parcat1
plot_data$BYGRP <- paste(plot_data$USUBJID, plot_data$PARCAT1, sep = " / ")
# Order panels in SAS BY order
by_order <- unique(plot_data$BYGRP)
plot_data$BYGRP <- factor(plot_data$BYGRP, levels = by_order)

n_panels <- length(by_order)
cat("Number of BY groups (USUBJID*PARCAT1):", n_panels, "\n")

# Titles from SAS:
# title1 "(page x of x)"
# title2 "Figure 16.2.5-x.x Individual concentration-time profiles"
# title3 "by compound, matrix, analyte and [actual/randomised][treatments/group]"
# title4 "Analysis Set : PK analysis set"
main_title <- "Figure 16.2.5-x.x Individual concentration-time profiles"
sub_title <- "by compound, matrix, analyte and [actual/randomised][treatments/group]\nAnalysis Set : PK analysis set  (page x of x)"
foot_txt <- paste0("Generated by R on ", format(Sys.Date(), "%Y-%m-%d"))

# SYMBOL1 INTERPOL=JOIN VALUE=NONE LINE=1 WIDTH=2 -> line only, no symbols
# Axis1 LABEL "Conc (ug/mL)", Axis2 LABEL "Time (hour)", FRAME
p <- ggplot(plot_data, aes(x = EACTM, y = AVAL, group = 1)) +
  geom_line(linewidth = 0.8, na.rm = TRUE) +
  facet_wrap(~ BYGRP) +
  labs(x = "Time (hour)", y = "Conc (ug/mL)",
       title = main_title, subtitle = sub_title, caption = foot_txt) +
  theme_bw(base_size = 10) +
  theme(
    panel.border = element_rect(colour = "black", fill = NA, linewidth = 0.8),
    strip.background = element_rect(fill = "grey90", colour = "black"),
    strip.text = element_text(size = 7),
    plot.title = element_text(hjust = 0.5, face = "bold", size = 11),
    plot.subtitle = element_text(hjust = 0.5, size = 10),
    plot.caption = element_text(hjust = 0, size = 7),
    axis.text = element_text(size = 7)
  )

# Size PNG dynamically so many individual panels remain readable
ncol_f <- if (n_panels <= 2) n_panels else if (n_panels <= 4) 2 else if (n_panels <= 9) 3 else 4
nrow_f <- ceiling(n_panels / ncol_f)
w_in <- min(20, 4 * ncol_f + 2)
h_in <- min(20, 3 * nrow_f + 2.5)
if (n_panels == 1) { w_in <- 8; h_in <- 6 }
if (n_panels > 60) {
  # Too many panels for one page: use spaghetti faceted by PARCAT1 to keep single PNG
  cat("Too many BY groups, switching to spaghetti by PARCAT1\n")
  p2 <- ggplot(plot_data, aes(x = EACTM, y = AVAL, group = USUBJID, colour = USUBJID)) +
    geom_line(linewidth = 0.6, na.rm = TRUE) +
    facet_wrap(~ PARCAT1) +
    labs(x = "Time (hour)", y = "Conc (ug/mL)",
         title = main_title, subtitle = sub_title, caption = foot_txt, colour = "Subject") +
    theme_bw(base_size = 10) +
    theme(
      panel.border = element_rect(colour = "black", fill = NA, linewidth = 0.8),
      plot.title = element_text(hjust = 0.5, face = "bold", size = 11),
      plot.subtitle = element_text(hjust = 0.5, size = 10),
      plot.caption = element_text(hjust = 0, size = 7),
      legend.position = "none"
    )
  ggsave(file.path(out, "sasgraph.png"), plot = p2, width = 10, height = 6, dpi = 150)
} else {
  ggsave(file.path(out, "sasgraph.png"), plot = p, width = w_in, height = h_in, dpi = 150)
}
cat("Wrote sasgraph.png\n")
