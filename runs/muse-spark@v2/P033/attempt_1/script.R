# P033_target12.sas -> R translation
# Figure 16.2.5-x.x Individual concentration-time profiles (GPLOT AVAL*eactm BY USUBJID parcat1)

suppressPackageStartupMessages({
  library(haven)
  library(dplyr)
  library(ggplot2)
})

out <- Sys.getenv("OUT_DIR")
if (out == "" || is.na(out)) out <- getwd()
if (!dir.exists(out)) dir.create(out, recursive = TRUE, showWarnings = FALSE)

# SAS round half away from zero (for compliance; not needed for plot)
round_half_up <- function(x, digits = 0) {
  ifelse(is.na(x), NA_real_,
         sign(x) * floor(abs(x) * 10^digits + 0.5) / 10^digits)
}

rawadam <- "D:/meta_hackathon/sas2r-agent/data/raw/cdisc-pilot/adam"

adsl_path <- file.path(rawadam, "adsl.xpt")
adpc_path <- file.path(rawadam, "adpc.xpt")

cat("Reading ADSL:", adsl_path, "\n")
adsl <- haven::read_xpt(adsl_path)
cat("Reading ADPC:", adpc_path, "\n")
adpc <- haven::read_xpt(adpc_path)

# Normalise names to uppercase for case-insensitive matching (SAS is case-insensitive)
names(adsl) <- toupper(names(adsl))
names(adpc) <- toupper(names(adpc))

cat(sprintf("ADSL: %d rows x %d cols\n", nrow(adsl), ncol(adsl)))
cat(sprintf("ADPC: %d rows x %d cols\n", nrow(adpc), ncol(adpc)))

# Columns used by SAS program: BY USUBJID parcat1 eactm ; PLOT AVAL * eactm
stopifnot("USUBJID" %in% names(adpc))
stopifnot("PARCAT1" %in% names(adpc))
stopifnot("EACTM" %in% names(adpc))
stopifnot("AVAL" %in% names(adpc))

# PROC SORT DATA=WORK.ADPC OUT=WORK.SORTadpc; BY USUBJID parcat1 eactm;
# SAS: missing sorts first, character ordering uppercase before lowercase (binary)
# Emulate missing-first explicitly
SORTadpc <- adpc %>%
  arrange(
    ifelse(is.na(USUBJID), 0L, 1L), USUBJID,
    ifelse(is.na(PARCAT1), 0L, 1L), PARCAT1,
    ifelse(is.na(EACTM), 0L, 1L), EACTM
  )

cat(sprintf("SORTadpc: %d rows\n", nrow(SORTadpc)))

# Titles (verbatim)
t1 <- "(page x of x)"
t2 <- "Figure 16.2.5-x.x Individual concentration-time profiles"
t3 <- "by compound, matrix, analyte and [actual/randomised][treatments/group]"
t4 <- "Analysis Set : PK analysis set"
full_title <- paste(t1, t2, t3, t4, sep = "\n")

# Footnote: Generated by the SAS System (&_SASSERVERNAME, &SYSSCPL) on <NLDATE20.> at <TIMEAMPM12.>
node <- tryCatch(unname(Sys.info()[["nodename"]]), error = function(e) "")
if (is.null(node) || is.na(node) || node == "") node <- "R"
foot_date <- format(Sys.Date(), "%B %d, %Y")
foot_time <- format(Sys.time(), "%I:%M:%S %p")
foot_time <- sub("^0", "", foot_time)
footnote1 <- sprintf("Generated by the SAS System (%s) on %s at %s", node, foot_date, foot_time)

# Prepare plot data: ensure numeric EACTM/AVAL for plotting, keep originals for CSV
plotdat <- SORTadpc
# Coerce EACTM/AVAL to numeric if stored as character/haven_labelled
plotdat$EACTM_N <- suppressWarnings(as.numeric(plotdat$EACTM))
plotdat$AVAL_N <- suppressWarnings(as.numeric(plotdat$AVAL))
# If coercion produced all NA but original was numeric-like labelled, fall back
if (all(is.na(plotdat$EACTM_N)) && !all(is.na(plotdat$EACTM))) {
  plotdat$EACTM_N <- suppressWarnings(as.numeric(as.character(plotdat$EACTM)))
}
if (all(is.na(plotdat$AVAL_N)) && !all(is.na(plotdat$AVAL))) {
  plotdat$AVAL_N <- suppressWarnings(as.numeric(as.character(plotdat$AVAL)))
}

# Drop rows with missing coordinates for line drawing (SAS GPLOT breaks/ignores them)
plotdat2 <- plotdat %>% filter(!is.na(EACTM_N) & !is.na(AVAL_N))

cat(sprintf("Plot rows (non-missing AVAL/EACTM): %d\n", nrow(plotdat2)))
stopifnot(nrow(plotdat2) > 0)

# BY groups
by_groups <- plotdat2 %>% distinct(USUBJID, PARCAT1)
n_panels <- nrow(by_groups)
cat(sprintf("BY groups (USUBJID x PARCAT1): %d\n", n_panels))
print(utils::head(as.data.frame(by_groups), 20))

# Build GPLOT equivalent: PLOT AVAL * eactm, INTERPOL=JOIN, VALUE=NONE, LINE=1, WIDTH=2
# One panel per BY USUBJID*PARCAT1 (SAS would page by BY group; combine via facet_wrap)
p <- ggplot(plotdat2, aes(x = EACTM_N, y = AVAL_N, group = 1)) +
  geom_line(linewidth = 0.8, color = "black") +
  facet_wrap(~ USUBJID + PARCAT1, scales = "free", labeller = labeller(.multi_line = TRUE)) +
  labs(
    title = full_title,
    x = "Time (hour)",
    y = "Conc (ug/mL)",
    caption = footnote1
  ) +
  theme_bw(base_size = 9) +
  theme(
    plot.title = element_text(hjust = 0.5, face = "plain", size = 11),
    axis.title = element_text(size = 10),
    axis.text = element_text(size = 8),
    strip.text = element_text(size = 7),
    strip.background = element_rect(fill = "white", colour = "black"),
    panel.border = element_rect(colour = "black", fill = NA, linewidth = 0.8),
    panel.grid.major = element_line(colour = "grey90", linewidth = 0.25),
    panel.grid.minor = element_blank(),
    plot.caption = element_text(hjust = 0, size = 7)
  )

# Dynamic size to accommodate many BY panels in a single PNG
ncol_f <- ifelse(n_panels <= 2, n_panels, ifelse(n_panels <= 6, 3L, 4L))
nrow_f <- ceiling(n_panels / ncol_f)
# Cap figure size to reasonable limits while keeping readability
w_in <- min(24, max(8, ncol_f * 4))
h_in <- min(32, max(6, nrow_f * 3 + 2))
cat(sprintf("Facets: %d panels (%d cols x %d rows), PNG %.1f x %.1f in\n", n_panels, ncol_f, nrow_f, w_in, h_in))

png_file <- file.path(out, "sasgraph.png")
ggsave(png_file, plot = p, width = w_in, height = h_in, dpi = 300, units = "in")
cat("Wrote figure:", png_file, "\n")

# Helper: format dates ISO for CSV (dates YYYY-MM-DD, datetimes YYYY-MM-DDTHH:MM:SS)
fmt_iso <- function(df) {
  df2 <- df
  for (nm in names(df2)) {
    v <- df2[[nm]]
    if (inherits(v, "POSIXt")) {
      df2[[nm]] <- format(v, "%Y-%m-%dT%H:%M:%S")
    } else if (inherits(v, "Date")) {
      df2[[nm]] <- format(v, "%Y-%m-%d")
    } else if (inherits(v, "haven_labelled")) {
      # preserve numeric values; convert labelled to plain
      df2[[nm]] <- haven::zap_labels(v)
      vv <- df2[[nm]]
      if (inherits(vv, "POSIXt")) df2[[nm]] <- format(vv, "%Y-%m-%dT%H:%M:%S")
      else if (inherits(vv, "Date")) df2[[nm]] <- format(vv, "%Y-%m-%d")
    }
  }
  df2
}

# CSV of the plotted data (sorted, as in WORK.SORTadpc)
csv_plot <- fmt_iso(as.data.frame(SORTadpc))
csv_file <- file.path(out, "sasgraph.csv")
write.csv(csv_plot, csv_file, row.names = FALSE, na = "")
cat("Wrote plotted data:", csv_file, "\n")

# Also write SORTadpc dataset counterpart (intermediate WORK dataset)
csv_sort <- file.path(out, "SORTadpc.csv")
write.csv(csv_plot, csv_sort, row.names = FALSE, na = "")
cat("Wrote dataset:", csv_sort, "\n")

# Plain-text rendering of the figure metadata (required table/listing .txt counterpart)
txt_file <- file.path(out, "sasgraph.txt")
