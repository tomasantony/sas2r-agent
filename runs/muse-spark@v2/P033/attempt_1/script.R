for (i in seq_len(nrow(by_groups))) {
  sub <- plotdat2 %>% filter(USUBJID == by_groups$USUBJID[i] & PARCAT1 == by_groups$PARCAT1[i])
  cat(sprintf("  %s / %s : n=%d  EACTM range=[%s, %s]  AVAL range=[%s, %s]\n",
              as.character(by_groups$USUBJID[i]),
